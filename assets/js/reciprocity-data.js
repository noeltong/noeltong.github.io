// Reciprocity-failure data for the film stocks archived in this site.
//
// Every stock entry names the official source used. Values are transcribed from the
// manufacturer datasheets stored under assets/filmarchive/docs/ ; where a manufacturer
// publishes no reciprocity data, the entry is marked with source "none" and no model,
// so the calculator shows an explicit "no official data" notice instead of inventing numbers.
//
// Model shapes:
//   { type: "table", points: [{ seconds, stops }] }
//       Piecewise-linear interpolation between published exposure times, in stops.
//   { type: "power", factor: P }
//       Ilford / HARMAN formula: corrected = metered ^ P (valid above 1 s).
//   { type: "seconds", points: [{ seconds, corrected }] }
//       Tables that publish the corrected exposure time directly (Adox, Rollei).
//   { type: "none", upToSeconds: N }
//       Official statement that no correction or filter compensation is needed up to
//       N seconds, with nothing published beyond that range.
//
// A stock with official: false carries community reference values rather than
// manufacturer-published data; the calculator labels it accordingly.

